//   bombardier : プレイヤーの近くまで飛んできて、頭上から樽を落とす（落下地点を表示）
//   builder   : 距離を取り、プレイヤーの行く手に柵を立てる
//   lobber    : 距離を取り、ものを山なりに投げる（落下地点を表示）
