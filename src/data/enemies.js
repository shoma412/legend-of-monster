//   roller  : 狙いをつけてから、まっすぐ転がってくる。通ったあとに汚水の床（踏むと減速）が残る
//   leech   : 飛びついて張り付き、HP を吸い続ける。ダッシュで振り払える
//   steamer : 動かない。予告の帯を出してから、蒸気を一直線に噴き続ける
