// 「ー」は、直前の母音を伸ばすだけなので、読まない。小さい「ッ・ャ・ュ・ョ」は、読まずに飛ばす（頭文字の並びなので、これで足りる）
export function romanizeKana(text, lang) {
  const index = lang === 'ko' ? 1 : 0;
  let out = '';
  for (const ch of text) {
    const pair = BASE[ch];
    if (pair) out += pair[index];
  }
  if (lang === 'ko') return out;
  return out.charAt(0).toUpperCase() + out.slice(1);
}

export const isKanaWord = (text) => /^[ァ-ヶー]+$/.test(text);
